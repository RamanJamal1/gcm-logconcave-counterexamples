#!/usr/bin/env python3
"""Exact reduced Boltzmann entropy integrands for p_t = (1/2) p_xx.

u_j = d^j(log p)/dx^j. H(p)=integral p log p (NOT Shannon entropy).
For a polynomial F in u_2,...,u_r,
 d/dt E_p F = E_p L(F),
 L(F) = -1/2 sum_ij F_ij u_(i+1)u_(j+1)
        +1/2 sum_i F_i sum_{k=1}^{i-1} binom(i,k)u_(k+1)u_(i-k+1).
This follows from the heat equation and two integrations by parts.
Gaussian tails with bounded smooth perturbations justify all boundary terms.
"""
from pathlib import Path
import json
import sympy as s
ROOT=Path(__file__).resolve().parents[1]
u={j:s.Symbol(f'u{j}') for j in range(1,33)}

def reduced_time_derivative(f):
    active=[j for j in range(2,32) if u[j] in f.free_symbols]
    out=0
    for i in active:
        for j in active:
            out-=s.diff(f,u[i],u[j])*u[i+1]*u[j+1]/2
        out+=s.diff(f,u[i])*sum(s.binomial(i,k)*u[k+1]*u[i-k+1] for k in range(1,i))/2
    return s.expand(out)

def derive(max_order=8):
    f={1:-u[1]**2/2,2:u[2]**2/2}
    for m in range(3,max_order+1):f[m]=reduced_time_derivative(f[m-1])
    return f

def main():
    formulas=derive()
    code=['"""Generated exact Boltzmann entropy integrands; heat generator 1/2 dxx.','Pass a dictionary u[j] of log-density derivatives (NumPy/JAX/Torch arrays).','Shannon entropy derivatives have the opposite sign.','"""','']
    latex=[r'% Generated by src/derive_integrands.py. H=\int p\log p, \partial_t p=\frac12\partial_x^2p.',r'\paragraph{Conventions and recurrence.}',r'Put $u_j=\partial_x^j\log p$, $H(p)=\int_{\mathbb R}p\log p$, and $\partial_t p=\tfrac12\partial_x^2p$. Then $I_m=\mathbb E_p F_m$, where $F_1=-u_1^2/2$, $F_2=u_2^2/2$, and',r'\[F_{m+1}=-\frac12\sum_{i,j}\partial_{u_i}\partial_{u_j}F_m\,u_{i+1}u_{j+1}+\frac12\sum_i\partial_{u_i}F_m\sum_{k=1}^{i-1}\binom{i}{k}u_{k+1}u_{i-k+1}.\]',r'The sums use only $i,j\ge2$. This recurrence eliminates $u_1$ by integration by parts and uses derivatives only through $u_m$ in $F_m$. No claim of uniqueness of the reduced representative is made. Shannon entropy is $-H$ and reverses every sign.']
    records={}
    for m,f in formulas.items():
        code+= [f'def integrand_{m}(u):']
        for j in range(1,m+1):
            if u[j] in f.free_symbols: code.append(f'    u{j} = u[{j}]')
        code.extend([f'    return {s.pycode(f)}',''])
        if m>=6:
            terms=s.Add.make_args(f)
            latex += [r'\begin{align*}',f'F_{{{m}}}={{}}& '+s.latex(terms[0])]
            for term in terms[1:]:
                latex.append(r'\\ &{}'+ ('-' +s.latex(-term) if term.could_extract_minus_sign() else '+'+s.latex(term)))
            latex.append(r'\end{align*}')
        record={'expression':str(f),'term_count':len(s.Add.make_args(f)),'max_derivative':max(int(str(x)[1:]) for x in f.free_symbols)}
        gaussian=s.expand(f.subs({u[1]:0,u[2]:-1,**{u[j]:0 for j in range(3,10)}})) if m>1 else -s.Rational(1,2)
        expected=(-1)**m*s.factorial(m-1)/2
        assert gaussian==expected,(m,gaussian,expected)
        record['standard_gaussian_exact']=str(gaussian)
        records[str(m)]=record
    code+=['INTEGRANDS = {'+', '.join(f'{m}: integrand_{m}' for m in formulas)+'}','']
    (ROOT/'src/generated_integrands.py').write_text('\n'.join(code))
    (ROOT/'paper/formulas.tex').write_text('\n'.join(latex)+'\n')
    result={'convention':'Boltzmann H=integral p log p; heat generator (1/2)dxx','recurrence':'integration-by-parts reduction, highest log-density derivative order m','formulas':records,'gaussian_checks':'passed exact symbolic equality for m=1,...,8'}
    (ROOT/'certs/formula_derivation.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({m:{k:v for k,v in r.items() if k!='expression'} for m,r in records.items()},indent=2))

if __name__=='__main__': main()
