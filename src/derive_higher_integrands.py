"""Export the same exact recurrence through order twelve for supplementary searches."""
from derive_integrands import derive,u
from pathlib import Path
import sympy as s,json
f=derive(12);lines=['# Generated by derive_higher_integrands.py; exact recurrence.'];records={}
for m,p in f.items():
 lines.append(f'def integrand_{m}(u):')
 for j in range(1,m+1):
  if u[j] in p.free_symbols:lines.append(f'    u{j}=u[{j}]')
 lines.extend([f'    return {s.pycode(p)}',''])
 v=p.subs({u[1]:0,u[2]:-1,**{u[j]:0 for j in range(3,13)}})
 if m>1:assert v==(-1)**m*s.factorial(m-1)/2
 records[m]={'terms':len(s.Add.make_args(p)),'gaussian':str(v) if m>1 else '-1/2'}
lines.append('INTEGRANDS={'+','.join(f'{m}:integrand_{m}' for m in f)+'}')
Path('src/generated_higher_integrands.py').write_text('\n'.join(lines)+'\n');Path('certs/higher_derivation.json').write_text(json.dumps(records,indent=2)+'\n');print(records)
